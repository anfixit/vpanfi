/*
 * Документы описываются структурой, а не размеченным текстом: нумерация
 * пунктов считается при отрисовке. В прошлой редакции номера были
 * вписаны руками, и после вставки одного пункта в середину вся ссылочная
 * нумерация ниже разъезжалась.
 */

export type LegalSection = {
  title: string;
  /** Пункты раздела. Нумеруются как «3.1», «3.2» автоматически. */
  items: readonly string[];
};

export type LegalDocument = {
  slug: "offer" | "privacy" | "rules";
  /** Заголовок документа и его же название в списке. */
  title: string;
  /*
   * Название в винительном падеже — для строки «Я принимаю …».
   * Склонять заголовок кодом нельзя: получалось «принимаю публичная
   * оферта».
   */
  titleAccusative: string;
  /** Одна строка о том, что это за документ. */
  summary: string;
  updatedAt: string;
  /** Абзацы перед нумерованными разделами. */
  preamble: readonly string[];
  sections: readonly LegalSection[];
};
